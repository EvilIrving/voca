package com.voca.speaker.domain

/**
 * 采集起不来的原因，带着界面那一句该说什么。
 *
 * 分段归类这件事是照微信输入法与豆包输入法的做法来的：微信把一次输入的结束收在
 * `VoiceInputEndCause` 十来档里，每一档带执行方与阶段；豆包的识别错误里明写
 * `NET_SWITCH`、`OFFLINE_SWITCH`、`SERVER_ERROR` 这些类型。好处不在好看，在于
 * 用户按住说话没反应时，界面能说出是哪一段不通，日志里也能分开统计。
 *
 * 这里只收采集这一段：链路没就绪、麦克风被别的应用拿走、没有录音权限、
 * 设备读写异常。识别与播放各有自己的失败类型。
 */
enum class CaptureFailure(val notice: String) {

    /** 实时链路没建起来或刚断掉，这时候按下说话连音频都送不出去。 */
    Offline("网络异常，正在重连"),

    /** 麦克风被通话或别的录音应用占着。 */
    Busy("麦克风被占用"),

    /** 系统没给录音权限。 */
    Permission("麦克风不可用，请检查权限"),

    /** 句柄打开了但读写异常，重启应用能恢复。 */
    Device("麦克风不可用，请重启应用"),
}
